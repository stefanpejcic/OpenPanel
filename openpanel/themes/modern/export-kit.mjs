// node themes/modern/export-kit.mjs: writes static/css/op.css, the op- kit for migrated panel pages, from src/app.css + src/panel.css
import { copyFileSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
let css = readFileSync(here('src/app.css'), 'utf8');

// cut a top-level block (selector line through its matching brace) and return [before, body, after]
function cut(src, head) {
  const start = src.indexOf(head);
  if (start < 0) throw new Error(`missing ${head}`);
  let depth = 0, i = src.indexOf('{', start);
  for (let j = i; j < src.length; j++) {
    if (src[j] === '{') depth++;
    else if (src[j] === '}' && --depth === 0) return [src.slice(0, start), src.slice(i + 1, j), src.slice(j + 1)];
  }
  throw new Error(`unclosed ${head}`);
}

// tailwind entry lines only matter to the theme pages build
css = css.replace(/^@(import|source|custom-variant)\b.*\n/gm, '').replace(/^\/\* (build from|same dark switch) .*\n/gm, '');
css = css.replaceAll('url("../fonts/', 'url("../vendor/fonts/inter/');

// tokens go on :root so the shell gets them on every page
let [a, theme, b] = cut(css, '@theme {');
css = `${a}:root {${theme}}${b}`;

// the theme pages' html rules become the scope's own
[a, , b] = cut(css, '@layer base {');
css = `${a}@layer components {
  .op-scope { background: var(--color-page); color: var(--color-body); font-family: var(--font-sans); font-size: 14px; line-height: 20px; -webkit-font-smoothing: antialiased; }
  .op-scope :focus-visible { outline: 2px solid var(--color-accent-text); outline-offset: 2px; }
}${b}`;

// radius and font names get an op- prefix so tailwind's rounded-* and font-* on old pages keep their values
const kit = `${css.trim()}\n\n${readFileSync(here('src/panel.css'), 'utf8').trim()}\n`.replace(/--radius-/g, '--op-radius-').replace(/--font-(sans|mono)\b/g, '--op-font-$1');
const out = `/* generated by themes/modern/export-kit.mjs from themes/modern/src/app.css and themes/modern/src/panel.css, edit those */\n${kit}`;
writeFileSync(here('../../static/css/op.css'), out);

for (const f of readdirSync(here('fonts'))) if (f.endsWith('.woff2')) copyFileSync(here(`fonts/${f}`), here(`../../static/vendor/fonts/inter/${f}`));
console.log(`static/css/op.css ${out.length} bytes`);
